#!/usr/bin/env python3
"""
=============================================================================
MICROSCOPIC SUMO CORRIDOR CALIBRATION & CORRELATION ENGINE
=============================================================================
This script orchestrates a multi-parametric Latin Hypercube Sample (LHS) sweep
across microscopic SUMO (libsumo) simulations on the Peak-Corridor sub-network
WITHOUT modifying `file2.py`.

What it does:
  1. Reads `results/calibration/corridor_peak_state.json` (generated by Step 1).
  2. Generates N orthogonal Latin Hypercube parameter vectors (α, β, γ, μ, λ).
  3. For each vector i, creates a run directory `results/calibration/run_XX/` and
     injects the parameter vector into that run's state JSON.
  4. Launches `file2.py` in parallel using a 3-worker pool on P-cores.
  5. Harvests performance telemetry across all N runs:
       - Market Disequilibrium Index (Ω)
       - Ride-Pooling Match Rate (P_pool %)
       - Average Passenger Wait Time (T_wait)
       - Total Fleet Vehicle Kilometers Traveled (VKT)
       - Passenger Rejection Rate (%)
  6. Computes the 5x5 Pearson & Spearman Correlation Matrix.
  7. Generates publication-ready plots and a full Markdown report:
       - `results/calibration/sumo_correlation_matrix.png`
       - `results/calibration/sumo_pareto_frontier.png`
       - `results/calibration/calibration_report.md`
=============================================================================
"""

