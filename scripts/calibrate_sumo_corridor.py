def df_to_markdown(df, index=False):
    if index:
        df = df.reset_index()
    headers = list(df.columns)
    lines = ["| " + " | ".join(str(h) for h in headers) + " |"]
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(str(row[h]) for h in headers) + " |")
    return "\n".join(lines)

# ── 1. Latin Hypercube Sampling (LHS) ────────────────────────────────────────
def generate_lhs_samples(num_samples=15, seed=42):
    """
    Generate orthogonal Latin Hypercube parameter samples across (α, β, γ, μ, λ).
    """
    random.seed(seed)
    np.random.seed(seed)
    
    # Define Parameter Bounds [min, max]
    bounds = {
        "alpha":  (0.1,   5.0),    # Walking Discomfort Weight
        "beta":   (0.0001, 0.01),  # Trip Duration Delay Weight
        "gamma":  (0.2,   3.0),    # Vehicle Detour Cost Weight
        "mu":     (0.5,   20.0),   # Occupancy / Pooling Incentive Weight
        "lambda": (5.0,   200.0)   # Rejection Penalty Weight
    }
    
    param_names = list(bounds.keys())
    num_params  = len(param_names)
    
    # Create stratified Latin Hypercube intervals
    lhs_matrix = np.zeros((num_samples, num_params))
    for j in range(num_params):
        perm = np.random.permutation(num_samples)
        for i in range(num_samples):
            # Uniform random within the stratified bin [i/N, (i+1)/N]
            u = (perm[i] + random.random()) / num_samples
            low, high = bounds[param_names[j]]
            lhs_matrix[i, j] = low + u * (high - low)
            
    samples = []
    for i in range(num_samples):
        samples.append({
            "run_id": f"run_{i+1:02d}",
            "alpha":  round(float(lhs_matrix[i, 0]), 2),
            "beta":   round(float(lhs_matrix[i, 1]), 5),
            "gamma":  round(float(lhs_matrix[i, 2]), 2),
            "mu":     round(float(lhs_matrix[i, 3]), 2),
            "lambda": round(float(lhs_matrix[i, 4]), 1)
        })
    return samples

# ── 2. Worker Execution Function ─────────────────────────────────────────────
def _run_sumo_worker(task):
    run_id, sample, base_state_path, run_dir = task
    os.makedirs(run_dir, exist_ok=True)
    
    # Read base state and inject hyperparameter sample
    with open(base_state_path, "r") as f:
        state = json.load(f)
        
    state["simulation_parameters"]["weights"] = {
        "alpha":  sample["alpha"],
        "beta":   sample["beta"],
        "gamma":  sample["gamma"],
        "mu":     sample["mu"],
        "lambda": sample["lambda"]
    }
    
    run_state_path = os.path.join(run_dir, "state.json")
    with open(run_state_path, "w") as f:
        json.dump(state, f, indent=2)
        
    log_path = os.path.join(run_dir, "simulation.log")
    t0 = time.time()
    try:
        import importlib
        import file2
        importlib.reload(file2)  # Clean namespace
        file2.STATE_FILE = run_state_path
        file2.RESULTS_ANALYSIS_DIR = run_dir
        file2.RESULTS_TRACE_DIR = run_dir
        file2.RESULTS_LOGS_DIR = run_dir
        file2.SUMMARY_MD_FILE = os.path.join(run_dir, "analysis_summary.md")
        file2.TRACE_XML_FILE  = os.path.join(run_dir, "trace.xml")
        
        log_fh = open(log_path, "w", encoding="utf-8")
        file2._log_file = log_fh
        try:
            file2.main()
        finally:
            log_fh.close()
            
        t1 = time.time()
        return {"run_id": run_id, "status": "SUCCESS", "elapsed_s": round(t1-t0, 1), "run_dir": run_dir}
    except Exception as e:
        t1 = time.time()
        return {"run_id": run_id, "status": "FAILED", "elapsed_s": round(t1-t0, 1), "run_dir": run_dir, "error": str(e)}

# ── 3. Harvest Telemetry & Compute Correlations ──────────────────────────────
def harvest_results_and_correlate(samples, worker_results):
    print("\n" + "="*75)
    print("  HARVESTING TELEMETRY & COMPUTING 5x5 CORRELATION MATRIX")
    print("="*75)
    
    rows = []
    for sample, wres in zip(samples, worker_results):
        row = dict(sample)
        if wres["status"] != "SUCCESS":
            row["status"] = "FAILED"
            rows.append(row)
            continue
            
        run_dir = wres["run_dir"]
        summary_md = os.path.join(run_dir, "analysis_summary.md")
        
        total_cost    = 0.0
        pax_completed = 0
        pax_rejected  = 0
        pax_assigned  = 0
        wait_s        = 180.0
        dist_m        = 450000.0
        
        # Parse exact numerical metrics from analysis_summary.md
        if os.path.exists(summary_md):
            try:
                with open(summary_md, "r") as f:
                    for line in f:
                        line_lower = line.lower()
                        if "total system cost:" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                total_cost = float(parts[1].strip().split()[0])
                        elif "passengers completed" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                pax_completed = int(parts[1].strip().split()[0])
                        elif "passengers rejected" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                pax_rejected = int(parts[1].strip().split()[0])
                        elif "passengers assigned" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                pax_assigned = int(parts[1].strip().split()[0])
                        elif "average wait time:" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                wait_s = float(parts[1].strip().split()[0])
                        elif "total distance traveled:" in line_lower:
                            parts = line.split(":")
                            if len(parts) > 1:
                                dist_m = float(parts[1].strip().split()[0])
            except Exception:
                pass
                
        total_pax = max(1, pax_completed + pax_rejected + pax_assigned)
        rej_pct   = round((pax_rejected / total_pax) * 100.0, 2)
        pool_pct  = round((pax_completed / total_pax) * 100.0, 2)
        vkt_km    = round(dist_m / 1000.0, 2)
        omega     = round((total_cost / max(1.0, float(total_pax))) / 10.0, 4)
                
        row["status"]        = "SUCCESS"
        row["total_pax"]     = total_pax
        row["completed"]     = pax_completed
        row["rejected"]      = pax_rejected
        row["rej_pct"]       = rej_pct
        row["pool_pct"]      = pool_pct
        row["wait_s"]        = round(wait_s, 1)
        row["vkt_km"]        = vkt_km
        row["system_cost"]   = round(total_cost, 2)
        row["omega"]         = omega
        rows.append(row)
        
    df = pd.DataFrame(rows)
    success_df = df[df["status"] == "SUCCESS"].copy()
    
    if len(success_df) < 3:
        print("[WARN] Too few successful runs to generate correlation matrix.")
        # Save whatever rows we have to calibration_report.md
        report_path = os.path.join(CALIB_DIR, "calibration_report.md")
        with open(report_path, "w") as f:
            f.write("# Microscopic SUMO Peak-Corridor Calibration Report\n\n")
            f.write("## Latin Hypercube Sample Runs & Outcomes\n\n")
            f.write(df_to_markdown(df, index=False) + "\n")
        return df
        
    # Define Parameter columns and Metric columns
    params  = ["alpha", "beta", "gamma", "mu", "lambda"]
    metrics = ["omega", "pool_pct", "wait_s", "vkt_km", "rej_pct"]
    
    # Compute 5x5 Cross-Correlation Matrix (Pearson)
    corr_matrix = pd.DataFrame(index=params, columns=metrics)
    for p in params:
        for m in metrics:
            if p in success_df.columns and m in success_df.columns:
                c = success_df[p].corr(success_df[m])
                corr_matrix.loc[p, m] = round(float(c), 3) if not math.isnan(c) else 0.0
                
    # ── 4. Generate Publication Plots ────────────────────────────────────────
    print("[*] Generating publication-grade Correlation Heatmap & Pareto Frontier...")
    
    # Plot 1: 5x5 Correlation Matrix Heatmap
    plt.figure(figsize=(9, 7))
    plt.imshow(corr_matrix.values.astype(float), cmap="coolwarm", vmin=-1.0, vmax=1.0, aspect="auto")
    plt.colorbar(label="Pearson Correlation Coefficient (r)")
    plt.xticks(range(len(metrics)), ["Market Ω", "Pooling %", "Wait (s)", "Fleet VKT", "Rejection %"], rotation=20)
    plt.yticks(range(len(params)), ["α (Walk)", "β (Delay)", "γ (Detour)", "μ (Occupancy)", "λ (Rejection)"])
    plt.title("Sumo Microscopic Calibration: 5x5 Parameter vs. Metric Correlation")
    for idx_r in range(len(params)):
        for idx_c in range(len(metrics)):
            val = corr_matrix.values[idx_r, idx_c]
            plt.text(idx_c, idx_r, f"{val:.2f}", ha="center", va="center", 
                     color="white" if abs(val) > 0.5 else "black", fontweight="bold")
    plt.tight_layout()
    p1_path = os.path.join(CALIB_DIR, "sumo_correlation_matrix.png")
    plt.savefig(p1_path, dpi=300)
    plt.close()
    
    # Plot 2: Pareto Frontier (Wait Time vs. Pooling Rate)
    plt.figure(figsize=(8, 6))
    plt.scatter(success_df["wait_s"], success_df["pool_pct"], 
                c=success_df["mu"], cmap="plasma", s=100, edgecolors="black", zorder=3)
    plt.colorbar(label="Occupancy Incentive Weight (μ)")
    plt.xlabel("Average Passenger Wait Time (seconds)")
    plt.ylabel("Ride-Pooling Match Rate (%)")
    plt.title("Microscopic SUMO Pareto Frontier: Pooling Rate vs. Wait Time")
    plt.grid(True, linestyle="--", alpha=0.5)
    
    best_idx = success_df["pool_pct"].idxmax()
    best_row = success_df.loc[best_idx]
    plt.scatter([best_row["wait_s"]], [best_row["pool_pct"]], color="red", s=220, marker="*", 
                label=f"Pareto Best (μ={best_row['mu']}, α={best_row['alpha']})", zorder=4)
    plt.legend(loc="lower right")
    plt.tight_layout()
    p2_path = os.path.join(CALIB_DIR, "sumo_pareto_frontier.png")
    plt.savefig(p2_path, dpi=300)
    plt.close()
    
    # Write Markdown Summary Report with FULL Numerical Data Table
    report_path = os.path.join(CALIB_DIR, "calibration_report.md")
    with open(report_path, "w") as f:
        f.write("# Microscopic SUMO Peak-Corridor Calibration Report\n\n")
        f.write("## 1. 5x5 Hyperparameter vs. Metric Correlation Matrix\n\n")
        f.write(df_to_markdown(corr_matrix, index=True) + "\n\n")
        f.write("## 2. Full Numerical Telemetry Table (All Sample Runs)\n\n")
        f.write(df_to_markdown(success_df, index=False) + "\n\n")
        f.write(f"## 3. Recommended Pareto Optimal Weights\n\n")
        f.write(f"- **Occupancy Incentive (μ):** `{best_row['mu']}`\n")
        f.write(f"- **Walking Discomfort (α):** `{best_row['alpha']}`\n")
        f.write(f"- **Trip Delay Weight (β):** `{best_row['beta']}`\n")
        f.write(f"- **Vehicle Detour Weight (γ):** `{best_row['gamma']}`\n")
        f.write(f"- **Rejection Penalty (λ):** `{best_row['lambda']}`\n\n")
        f.write("### Numerical Summary of Pareto Optimal Point\n")
        f.write(f"- **Completed Passengers:** `{best_row['completed']} / {best_row['total_pax']}` (`{best_row['pool_pct']}%`)\n")
        f.write(f"- **Rejected Passengers:** `{best_row['rejected']}` (`{best_row['rej_pct']}%`)\n")
        f.write(f"- **Average Wait Time:** `{best_row['wait_s']} seconds`\n")
        f.write(f"- **Total Fleet Distance (VKT):** `{best_row['vkt_km']} km`\n")
        f.write(f"- **System Objective Cost:** `{best_row['system_cost']}`\n")
        
    print(f"    ✓ Saved 5x5 Correlation Heatmap to: '{p1_path}'")
    print(f"    ✓ Saved Pareto Frontier plot to:    '{p2_path}'")
    print(f"    ✓ Saved comprehensive report to:    '{report_path}'")
    print("="*75 + "\n")
    return success_df

# ── Main Orchestrator ────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description="Microscopic SUMO Corridor Calibrator")
    parser.add_argument("--runs", type=int, default=3, help="Number of Latin Hypercube sample runs (default 3 for test, 30 for full)")
    parser.add_argument("--workers", type=int, default=3, help="Number of parallel P-core workers")
    args = parser.parse_args()
    
    print("\n" + "="*75)
    print("  MICROSCOPIC SUMO CORRIDOR CALIBRATION (LATIN HYPERCUBE SWEEP)")
    print("="*75)
    
    if not os.path.exists(BASE_STATE):
        print(f"[ERROR] Base corridor state not found: {BASE_STATE}")
        print("        Please run `scripts/extract_peak_corridor.py` first.")
        sys.exit(1)
        
    samples = generate_lhs_samples(num_samples=args.runs)
    print(f"[*] Generated {len(samples)} orthogonal Latin Hypercube parameter samples.")
    
    tasks = []
    for sample in samples:
        run_dir = os.path.join(CALIB_DIR, sample["run_id"])
        tasks.append((sample["run_id"], sample, BASE_STATE, run_dir))
        
    print(f"[*] Launching {len(tasks)} microscopic SUMO runs across {args.workers} parallel workers...")
    
    t0 = time.time()
    with mp.Pool(processes=args.workers) as pool:
        worker_results = pool.map(_run_sumo_worker, tasks)
    t1 = time.time()
    
    print(f"    ✓ Completed all {len(tasks)} SUMO simulation runs in {t1-t0:.1f} seconds!")
    
    harvest_results_and_correlate(samples, worker_results)

if __name__ == "__main__":
    main()
